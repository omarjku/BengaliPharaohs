// Builds the voice script for every audio clip from the app's own text (public/data/cards.json + UI strings),
// so the audio always matches what is on screen. Run again after any Bangla change:
//   node scripts/gen-audio-script.mjs
// Writes audio/script.json (input for scripts/tts.py) and ../docs/audio-script.md (to read/check by a human).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const cards = JSON.parse(readFileSync(new URL("public/data/cards.json", root), "utf8"));

// Screen text and the spoken-question list come straight from the app (Node strips the TypeScript types).
const { S } = await import(new URL("src/lib/strings.ts", root).href);
const { QUESTION_CLIPS } = await import(new URL("src/lib/voice-questions.ts", root).href);
const bnOf = (key) => {
  if (!S[key]) throw new Error(`string ${key} not found`);
  return S[key].bn;
};
/** "Question. Hint. Option one, option two, option three." */
const question = ({ q, opts }) => {
  const head = q.map((k) => bnOf(k).replace(/[।?]?$/, (m) => m || "।")).join(" ");
  return opts?.length ? `${head} ${opts.map(bnOf).join(", ")}।` : head;
};

/** Dates, deadlines and reasons are shown on screen only; the voice says "the date on the screen". */
function generic(text) {
  return text
    .replace(/\s*তারিখ: \{date\}।/g, "")
    .replace("শেষ তারিখ ছিল {deadline}।", "শেষ তারিখ স্ক্রিনে দেখানো আছে।")
    .replace(/\{deadline\}-এর/g, "স্ক্রিনে দেখানো তারিখের")
    .replace(/\{deadline\}/g, "স্ক্রিনে দেখানো তারিখ")
    .replace(/\s*\{reason\}/g, "");
}

/** Make text easy for a TTS voice: no brackets, no English abbreviations, phone number digit by digit. */
function speakable(text) {
  return text
    .replace(/১৬১২৩/g, "এক ছয় এক দুই তিন")
    .replace(/\s*\(SAAO\)/g, "")
    .replace(/SAAO/g, "কৃষি অফিসার")
    .replace(/DAE-নিবন্ধিত/g, "কৃষি সম্প্রসারণ অধিদপ্তরে নিবন্ধিত")
    .replace(/DAE-এর/g, "কৃষি সম্প্রসারণ অধিদপ্তরের")
    .replace(/BRRI-এর/g, "ব্রির")
    .replace(/BRRI/g, "ব্রি")
    .replace(/IRRI/g, "ইরি")
    .replace(/\s*\(নিশ্চিত নই\)/g, ", তবে নিশ্চিত নই")
    .replace(/\s*\(লিফ স্ক্যাল্ড\)/g, "")
    .replace(/\s*\(ঘাড়ের\)/g, "")
    .replace(/২-৩/g, "দুই থেকে তিন")
    .replace(/২-৪/g, "দুই থেকে চার")
    .replace(/৪-৫টা/g, "চার থেকে পাঁচটা")
    .replace(/\s*\(([^)]*)\)/g, ", $1,") // other brackets → a short pause
    .replace(/\s*\/\s*/g, " বা ")
    .replace(/,\s*([,।?])/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

const body = (id, overrides = {}) => cards.cards[id].parts.map((p, i) => overrides[i] ?? generic(p.bn)).join(" ");
const A1 = cards.cards.A1;
const a1Body = (outlook) =>
  body("A1", {
    0: "আপনার দেওয়া তথ্য স্ক্রিনে দেখানো আছে।",
    1: generic(A1.parts[1].bn).replace("{outlook}", A1.extra[outlook].bn),
  });

const clips = [
  // Photo results: card body = parts 1–4.
  ...["C1", "C2", "C3", "C4", "C5", "C6", "C7", "C8", "C9"].map((id) => ({ id: cards.cards[id].clip, card: id, text: body(id) })),
  // Flood/drought results.
  { id: "A1-SURVIVE-USUAL", card: "A1", text: a1Body("usually_survives") },
  { id: "A1-SURVIVE-UNSURE", card: "A1", text: a1Body("not_sure") },
  { id: "A1-BACKUP", card: "A1", text: A1.extra.backup.bn },
  ...["A2", "A3", "A4", "A5", "A6", "A7"].map((id) => ({ id: cards.cards[id].clip, card: id, text: body(id) })),
  // "Why not sure" reasons (several reason codes share one clip).
  ...Object.values(
    Object.fromEntries(Object.values(cards.reasons).map((r) => [r.clip, { id: r.clip, card: "A6 reason", text: r.bn }])),
  ),
  // Shared lines played after every card.
  ...Object.entries(cards.shared).map(([id, s]) => ({ id, card: "shared", text: s.bn })),
  // App prompts.
  { id: "UI-CONSENT", card: "share", text: `${bnOf("share_title")} ${bnOf("share_body")}` },
  { id: "UI-QUEUED", card: "share", text: bnOf("share_queued") },
  { id: "UI-OFFLINE-OK", card: "home", text: bnOf("selfcheck_ok") },
  // Spoken questions (🔊 next to each question).
  ...Object.entries(QUESTION_CLIPS).map(([id, q]) => ({ id, card: "question", text: question(q) })),
].map((c) => ({ ...c, text: speakable(c.text) }));

mkdirSync(new URL("audio/", root), { recursive: true });
writeFileSync(new URL("audio/script.json", root), JSON.stringify(clips, null, 2) + "\n");

const md = [
  "# Audio script (generated — do not edit by hand)",
  "",
  "Generated by `frontend/scripts/gen-audio-script.mjs` from `frontend/public/data/cards.json` and `frontend/src/lib/strings.ts`.",
  "To change a line, change the app text there, then re-run the script. Dates are never spoken (\"the date on the screen\").",
  "",
  `${clips.length} clips. File name = \`frontend/public/audio/<clip id>.mp3\`.`,
  "",
  "| # | Clip id | Used for | Bangla (as spoken) |",
  "|---|---|---|---|",
  ...clips.map((c, i) => `| ${i + 1} | \`${c.id}\` | ${c.card} | ${c.text} |`),
  "",
].join("\n");
writeFileSync(new URL("../docs/audio-script.md", root), md);
console.log(`${clips.length} clips → audio/script.json and docs/audio-script.md`);
